const dictionaries: Record<Locale, Dict> = { zh, en }

let currentLocale: Locale = 'zh'

export function setLocale(locale: Locale): void {
  currentLocale = locale
  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'
  try {
    localStorage.setItem('flowread.locale', locale)
  } catch {
    /* private mode */
  }
}

export function getLocale(): Locale {
  return currentLocale
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[locale] ?? dictionaries.zh
  let value = dict[key] ?? dictionaries.zh[key] ?? key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

export function t(key: string, vars?: Record<string, string | number>): string {
  return translate(currentLocale, key, vars)
}

export function createTranslator(locale: Locale): (key: string, vars?: Record<string, string | number>) => string {
  return (key, vars) => translate(locale, key, vars)
}

